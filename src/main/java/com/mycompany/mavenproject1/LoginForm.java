    /** Memvalidasi masukan, memeriksa akun ke database, lalu membuka Beranda. */
    private void prosesLogin() {
        String username = txtUsername.getText().trim();
        String sandi = new String(txtPassword.getPassword());
        if (username.isEmpty() || sandi.isEmpty()) {
            lblError.setText("Username dan kata sandi wajib diisi.");
            return;
        }
        try {
            Pengguna p = auth.login(username, sandi);
            if (p == null) {
                lblError.setText("Username atau kata sandi salah.");
                txtPassword.setText("");
                return;
            }
            dispose();
            new BerandaFrame(p).setVisible(true);
        } catch (SQLException ex) {
            lblError.setText("Kesalahan database: " + ex.getMessage());
        }
    }

